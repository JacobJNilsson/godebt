// realTempDir returns a temporary directory without symbolic links, as Walk reports its root.
func realTempDir(t *testing.T) string {
	t.Helper()
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	return root
}

// lock gives paths under root mode 000 until the test ends.
func lock(t *testing.T, root string, paths ...string) {
	t.Helper()
	if os.Geteuid() == 0 {
		t.Skip("root reads files with mode 000")
	}
	for _, path := range paths {
		abs := filepath.Join(root, filepath.FromSlash(path))
		if err := os.Chmod(abs, 0); err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { _ = os.Chmod(abs, 0o755) })
	}
}

