func TestWalkKeepsSyntaxOfMeasuredFiles(t *testing.T) {
	root := t.TempDir()
	write(t, root, map[string]string{
		"ok.go":  "package p\n\nfunc F() {}\n",
		"bad.go": "package p\n\nfunc (\n",
		"x.md":   "text\n",
	})
	tree := walk(t, root, Options{})
	for _, f := range tree.Files {
		switch f.Path {
		case "ok.go":
			if f.Syntax == nil || f.ParseErr != nil || len(f.Src) == 0 {
				t.Errorf("ok.go: syntax %v, error %v, %d source bytes", f.Syntax, f.ParseErr, len(f.Src))
			}
		case "bad.go":
			if f.ParseErr == nil {
				t.Error("bad.go: no parse error")
			}
		case "x.md":
			if f.Syntax != nil || f.Src != nil {
				t.Error("x.md: an unsupported file keeps no source")
			}
		}
	}
}

