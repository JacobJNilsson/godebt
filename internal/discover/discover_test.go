var errMidRead = errors.New("device error")

// failingReader returns its data, then fails every later read.
type failingReader struct{ data []byte }

func (r *failingReader) Read(p []byte) (int, error) {
	if len(r.data) == 0 {
		return 0, errMidRead
	}
	n := copy(p, r.data)
	r.data = r.data[n:]
	return n, nil
}

func TestIgnoreErrorRecordsAReadFailure(t *testing.T) {
	root := realTempDir(t)
	w := &walker{root: root, tree: &Tree{ReadErrors: []ReadError{}}}
	file := filepath.Join(root, "g", ".gitignore")
	// The handler adds the file name to the position, as the library does for a file that it opens.
	handler := func(e gitignore.Error) bool {
		p := e.Position()
		p.File = file
		return w.ignoreError(gitignore.NewError(e.Underlying(), p))
	}
	done := make(chan struct{})
	go func() {
		gitignore.New(&failingReader{data: []byte("a.go\nb")}, filepath.Dir(file), handler)
		close(done)
	}()
	select {
	case <-done:
	case <-time.After(5 * time.Second):
		t.Fatal("the parser did not stop after a failed read")
	}
	want := []ReadError{{Path: "g/.gitignore", Message: "device error"}}
	if !reflect.DeepEqual(w.tree.ReadErrors, want) {
		t.Errorf("read errors = %+v, want %+v", w.tree.ReadErrors, want)
	}
}

func TestIgnoreErrorDecisions(t *testing.T) {
	root := realTempDir(t)
	cases := []struct {
		name       string
		err        gitignore.Error
		wantResult bool
		wantErrors []ReadError
	}{
		{"invalid pattern", gitignore.NewError(gitignore.ErrInvalidPatternError, gitignore.Position{Line: 1}), true, []ReadError{}},
		{"carriage return", gitignore.NewError(gitignore.ErrCarriageReturnError, gitignore.Position{Line: 1}), true, []ReadError{}},
		{"missing file", gitignore.NewError(&fs.PathError{Op: "open", Path: filepath.Join(root, ".gitignore"), Err: fs.ErrNotExist}, gitignore.Position{}), true, []ReadError{}},
		{
			"failed open", gitignore.NewError(&fs.PathError{Op: "open", Path: filepath.Join(root, "d", ".gitignore"), Err: fs.ErrPermission}, gitignore.Position{}),
			false, []ReadError{{Path: "d/.gitignore", Message: "open: permission denied"}},
		},
		{"no file", gitignore.NewError(errMidRead, gitignore.Position{}), false, []ReadError{{Path: ".", Message: "device error"}}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			w := &walker{root: root, tree: &Tree{ReadErrors: []ReadError{}}}
			if got := w.ignoreError(tc.err); got != tc.wantResult {
				t.Errorf("result = %v, want %v", got, tc.wantResult)
			}
			if !reflect.DeepEqual(w.tree.ReadErrors, tc.wantErrors) {
				t.Errorf("read errors = %+v, want %+v", w.tree.ReadErrors, tc.wantErrors)
			}
		})
	}
}

// walkWithin fails the test when the walk does not end within five seconds.
// A loop inside the library never checks the context, so the walk runs in its own goroutine.
func walkWithin(t *testing.T, root string) *Tree {
	t.Helper()
	type result struct {
		tree *Tree
		err  error
	}
	done := make(chan result, 1)
	go func() {
		tree, err := Walk(context.Background(), root, Options{})
		done <- result{tree, err}
	}()
	select {
	case r := <-done:
		if r.err != nil {
			t.Fatalf("Walk(%s): %v", root, r.err)
		}
		return r.tree
	case <-time.After(5 * time.Second):
		t.Fatalf("Walk(%s) did not end within five seconds", root)
		return nil
	}
}

